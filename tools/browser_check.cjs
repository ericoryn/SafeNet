/* Проверка только отдельной локальной демо-базы; production URL запрещён. */
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const origin = process.argv[2] || 'http://127.0.0.1:8511';
assert.equal(new URL(origin).hostname, '127.0.0.1');
assert.equal(new URL(origin).port, '8511');

(async () => {
  const browser = await chromium.launch({channel: 'chrome', headless: true});
  const context = await browser.newContext({viewport: {width: 1440, height: 1000}, reducedMotion: 'reduce'});
  const page = await context.newPage();
  const errors = [], checks = [];
  page.on('pageerror', error => errors.push(error.message));
  const output = path.resolve('reports/ux_refinement');
  fs.mkdirSync(output, {recursive: true});
  try {
    await page.goto(origin);
    await page.locator('#cases .row-title').first().waitFor();
    await page.screenshot({path: path.join(output, 'ru-desktop.png'), fullPage: false});
    const sourcePreview = await page.locator('#cases .row-title').first().textContent();
    await page.locator('[data-locale="kk"]').click();
    await page.waitForFunction(() => document.documentElement.lang === 'kk' && document.querySelector('#list-count').textContent === 'Тексеру кезегі');
    assert.equal(await page.locator('#materials-title').textContent(), 'Материалдар');
    assert.equal(await page.locator('#cases .row-title').first().textContent(), sourcePreview);
    checks.push('language_switch_and_original_text');
    await page.screenshot({path: path.join(output, 'kk-desktop.png'), fullPage: true});
    await page.locator('#cases .row-title').first().click();
    await page.locator('#detail .decision-actions').waitFor();
    await page.getByRole('heading', {name: 'Тәуекел бағасы', exact: true}).waitFor();
    for (const name of ['Белгілерді растау', 'Жалған анықтау', 'Тексеру сұрату']) {
      const response = page.waitForResponse(r => r.url().endsWith('/decisions') && r.request().method() === 'POST');
      await page.getByRole('button', {name, exact: true}).click();
      assert.equal((await response).status(), 200);
      await page.waitForFunction(() => document.querySelector('#message').textContent.includes('Шешім сақталды'));
    }
    await page.waitForFunction(() => document.querySelectorAll('#history li').length >= 3);
    checks.push('three_decisions_saved');
    const oldVersions = await page.locator('#detail select option').count();
    await page.getByRole('button', {name: 'Талдауды қайталау', exact: true}).click();
    await page.waitForFunction(count => document.querySelectorAll('#detail select option').length > count, oldVersions);
    checks.push('reanalysis_new_version');
    await page.getByRole('button', {name: 'Байланыстарды ашу', exact: true}).click();
    await page.locator('#graph .graph-node').first().waitFor();
    await page.locator('#graph .graph-node').last().click();
    await page.getByRole('heading', {name: 'Материалдар хронологиясы'}).waitFor();
    await page.screenshot({path: path.join(output, 'kk-graph.png'), fullPage: true});
    checks.push('graph_nodes_and_timeline');
    await page.locator('[data-view="overview"]').click();
    await page.waitForFunction(() => !document.querySelector('#overview-view').hidden);
    await page.locator('[data-locale="ru"]').click();
    await page.waitForFunction(() => document.documentElement.lang === 'ru');
    assert.equal(await page.locator('#overview-title').textContent(), 'Сводка');
    await page.locator('[data-view="materials"]').click();
    await page.locator('#open-upload').click();
    await page.locator('#submit-upload').click();
    await page.locator('#upload-error').waitFor({state: 'visible'});
    assert.equal(await page.locator('#upload-error').textContent(), 'Введите текст.');
    const text = 'Синтетический приёмочный пример. Қатысу тегін. Жеңімпаз кездейсоқ таңдалады.';
    await page.locator('textarea[name="text"]').fill(text);
    await page.locator('#submit-upload').click();
    await page.waitForFunction(() => document.querySelector('#source')?.textContent.includes('Синтетический приёмочный пример'));
    assert.equal(await page.locator('#source').textContent(), text);
    const caseHash = new URL(page.url()).hash;
    await page.reload();
    await page.locator('#source').waitFor();
    assert.equal(await page.locator('#source').textContent(), text);
    assert.equal(new URL(page.url()).hash, caseHash);
    checks.push('upload_validation_processing_and_reload');
    await page.locator('#close-detail').click();
    await page.locator('[data-locale="kk"]').click();
    await page.reload();
    await page.locator('#cases .row-title').first().waitFor();
    assert.equal(await page.locator('html').getAttribute('lang'), 'kk');
    checks.push('language_persisted_on_reload');

    await page.locator('[data-locale="ru"]').click();
    await page.waitForFunction(() => document.documentElement.lang === 'ru');
    const unavailable = route => route.fulfill({status: 503, contentType: 'application/json', body: JSON.stringify({error_code: 'backend_unavailable'})});
    await page.route('**/backend/summary', unavailable);
    await page.goto(origin + '/' + caseHash);
    await page.reload();
    await page.locator('#source').waitFor();
    assert.equal(await page.locator('#source').textContent(), text);
    assert.equal(new URL(page.url()).hash, caseHash);
    await page.waitForFunction(() => document.querySelector('#overview-feedback').getAttribute('role') === 'alert');
    checks.push('summary_failure_does_not_block_case_deep_link');
    await page.unroute('**/backend/summary', unavailable);
    await page.locator('[data-view="overview"]').click();
    await page.locator('#overview-feedback button').click();
    await page.waitForFunction(() => /^\d+$/.test(document.querySelector('#total').textContent) && document.querySelector('#overview-feedback').getAttribute('role') !== 'alert');
    const totalBeforeFailure = await page.locator('#total').textContent();
    await page.route('**/backend/summary', unavailable);
    await page.locator('#overview-refresh').click();
    await page.waitForFunction(() => document.querySelector('#overview-feedback').getAttribute('role') === 'alert');
    assert.equal(await page.locator('#total').textContent(), totalBeforeFailure);
    await page.screenshot({path: path.join(output, 'overview-error.png'), fullPage: false});
    await page.unroute('**/backend/summary', unavailable);
    await page.locator('#overview-feedback button').click();
    await page.waitForFunction(() => document.querySelector('#overview-feedback').getAttribute('role') !== 'alert');
    assert.equal(await page.locator('#total').textContent(), totalBeforeFailure);
    assert.equal(await page.evaluate(() => document.activeElement.id), 'overview-title');
    checks.push('overview_error_preserves_values_and_retry_recovers');

    const graphFailurePattern = /\/backend\/cases\/[^/]+\/graph(?:\?|$)/;
    await page.route(graphFailurePattern, unavailable);
    await page.goto(origin + '/' + caseHash.replace('#materials', '#graph'));
    await page.locator('#graph .empty-state button').waitFor();
    assert.match(await page.locator('#graph').textContent(), /Не удалось загрузить граф/);
    assert.doesNotMatch(await page.locator('#graph').textContent(), /после успешного анализа/);
    await page.unroute(graphFailurePattern, unavailable);
    await page.locator('#graph .empty-state button').click();
    await page.locator('#graph .graph-node').first().waitFor();
    assert.equal(await page.evaluate(() => document.activeElement.id), 'graph-title');
    checks.push('graph_network_error_has_retry_and_recovers');

    const emptyCases = route => route.fulfill({status: 200, contentType: 'application/json', body: JSON.stringify({items: [], next_cursor: null})});
    const casesPattern = /\/backend\/cases\?/;
    await page.route(casesPattern, emptyCases);
    await page.goto(origin + '/#graph');
    await page.reload();
    await page.waitForFunction(() => document.querySelector('#graph').textContent.includes('Добавьте материал'));
    assert.doesNotMatch(await page.locator('#graph-inspector').textContent(), /Загрузка/);
    assert.equal(await page.locator('#graph .graph-node').count(), 0);
    await page.screenshot({path: path.join(output, 'graph-empty.png'), fullPage: false});
    await page.unroute(casesPattern, emptyCases);
    await page.goto(origin + '/#materials');
    await page.reload();
    await page.locator('#cases .row-title').first().waitFor();
    checks.push('empty_graph_has_no_endless_loading');

    const pendingCaseUrl = origin + '/backend/cases/' + new URLSearchParams(caseHash.split('?')[1]).get('case');
    const pendingCase = async route => {
      const response = await route.fetch();
      const data = await response.json();
      await route.fulfill({response, json: {...data, case: {...data.case, status: 'processing'}, latest_result: null}});
    };
    await page.route(pendingCaseUrl, pendingCase);
    await page.goto(origin + '/' + caseHash);
    await page.locator('.detail-jump').waitFor();
    assert.equal(await page.locator('.detail-jump').isDisabled(), true);
    assert.equal(await page.locator('#decision-actions button:disabled').count(), 3);
    assert.match(await page.locator('#tracks').textContent(), /Результат пока отсутствует/);
    await page.unroute(pendingCaseUrl, pendingCase);
    await page.locator('#close-detail').click();
    checks.push('pending_case_disables_decision_jump_and_actions');

    await page.emulateMedia({reducedMotion: 'no-preference'});
    const animated = await page.locator('#materials-view').evaluate(element => ({name: getComputedStyle(element).animationName, duration: getComputedStyle(element).animationDuration}));
    assert.notEqual(animated.name, 'none');
    assert(animated.duration.split(',').some(value => parseFloat(value) > 0));
    await page.emulateMedia({reducedMotion: 'reduce'});
    const motion = await page.locator('#materials-view').evaluate(element => ({animation: getComputedStyle(element).animationDuration, transition: getComputedStyle(element).transitionDuration}));
    assert(motion.animation.split(',').every(value => parseFloat(value) === 0), JSON.stringify(motion));
    assert(motion.transition.split(',').every(value => parseFloat(value) === 0), JSON.stringify(motion));
    checks.push('motion_enabled_only_without_reduced_motion');

    await page.setViewportSize({width: 390, height: 844});
    await page.locator('#toggle-filters').click();
    assert.equal(await page.locator('#toggle-filters').getAttribute('aria-expanded'), 'true');
    assert.equal(await page.locator('#filters').getAttribute('data-expanded'), 'true');
    await page.locator('#filters select[name="language"]').selectOption('ru');
    await page.waitForFunction(() => document.querySelector('.case-list').getAttribute('aria-busy') === 'false');
    assert.equal((await page.locator('#filter-count').textContent()).trim(), '1');
    await page.locator('#toggle-filters').click();
    assert.equal(await page.locator('#filters select[name="language"]').isVisible(), false);
    assert.equal(await page.locator('#filters select[name="language"]').inputValue(), 'ru');
    await page.locator('#reset-filters').click();
    await page.waitForFunction(() => document.querySelector('.case-list').getAttribute('aria-busy') === 'false');
    assert.equal(await page.locator('#filters select[name="language"]').inputValue(), '');
    assert.equal(await page.locator('#filter-count').isVisible(), false);
    checks.push('mobile_filter_disclosure_preserves_values_and_reset');

    await page.locator('#toggle-filters').click();
    await page.locator('#filters input[name="since"]').fill('2099-01-02');
    await page.locator('#filters input[name="until"]').fill('2000-01-01');
    await page.locator('#filters input[name="until"]').press('Tab');
    assert.equal(await page.locator('#filters input[name="until"]').evaluate(element => element.validity.valid), false);
    await page.locator('#toggle-filters').click();
    await page.locator('#filters select[name="track"]').selectOption('casino');
    assert.equal(await page.locator('#filters').getAttribute('data-expanded'), 'true');
    assert.equal(await page.locator('#filters input[name="until"]').isVisible(), true);
    await page.locator('#filters input[name="since"]').fill('2000-01-01');
    await page.locator('#filters input[name="until"]').fill('2099-01-02');
    await page.locator('#filters input[name="until"]').press('Tab');
    await page.waitForFunction(() => document.querySelector('.case-list').getAttribute('aria-busy') === 'false');
    assert.equal(await page.locator('#filters input[name="until"]').evaluate(element => element.validity.valid), true);
    await page.locator('#reset-filters').click();
    await page.waitForFunction(() => document.querySelector('.case-list').getAttribute('aria-busy') === 'false');
    await page.locator('#toggle-filters').click();
    await page.evaluate(() => window.scrollTo(0, 0));
    await page.screenshot({path: path.join(output, 'ru-mobile.png'), fullPage: false});
    checks.push('invalid_hidden_date_range_reopens_filters_and_correction_recovers');

    const firstMaterial = page.locator('#cases .row-title').first();
    const focusedCase = await firstMaterial.evaluate(element => element.closest('tr').dataset.id);
    await firstMaterial.focus();
    await page.keyboard.press('Enter');
    await page.locator('#detail .decision-actions').waitFor();
    await page.locator('.detail-jump').click();
    assert.equal(await page.evaluate(() => document.activeElement.id), 'decision-actions');
    assert.equal(await page.locator('#detail-shell').getAttribute('aria-modal'), 'true');
    await page.locator('#close-detail').focus();
    await page.keyboard.press('Shift+Tab');
    assert.equal(await page.evaluate(() => document.querySelector('#detail-shell').contains(document.activeElement) && document.activeElement.id !== 'close-detail'), true);
    await page.keyboard.press('Tab');
    assert.equal(await page.evaluate(() => document.activeElement.id), 'close-detail');
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#detail-shell').isVisible(), false);
    assert.equal(await page.evaluate(() => document.activeElement.closest('tr')?.dataset.id), focusedCase);
    checks.push('decision_jump_keyboard_modal_trap_and_escape_focus_return');

    await page.locator('[data-locale="kk"]').click();
    await page.waitForFunction(() => document.documentElement.lang === 'kk');
    for (const width of [768, 390, 320]) {
      await page.setViewportSize({width, height: 900});
      for (const view of ['materials', 'graph', 'overview']) {
        await page.locator(`[data-view="${view}"]`).click();
        await page.waitForFunction(v => !document.querySelector('#' + v + '-view').hidden, view);
        if (view === 'graph') await page.locator('.graph-node').first().waitFor();
        const geometry = await page.evaluate(() => ({content: document.documentElement.scrollWidth, viewport: innerWidth}));
        assert(geometry.content <= geometry.viewport + 1, JSON.stringify({width, view, geometry}));
      }
      await page.locator('[data-view="materials"]').click();
      await page.evaluate(() => window.scrollTo(0, 0));
      await page.screenshot({path: path.join(output, `kk-${width}.png`), fullPage: true});
      await page.locator('#open-upload').click();
      const dialogGeometry = await page.locator('#upload').evaluate(element => ({left: element.getBoundingClientRect().left, right: element.getBoundingClientRect().right, scroll: element.scrollWidth, width: element.clientWidth, viewport: innerWidth}));
      assert(dialogGeometry.left >= 0 && dialogGeometry.right <= dialogGeometry.viewport && dialogGeometry.scroll <= dialogGeometry.width + 1, JSON.stringify({width, dialogGeometry}));
      await page.locator('#close-upload').focus();
      await page.keyboard.press('Shift+Tab');
      // Native dialogs may visit browser chrome before wrapping; background controls must stay inert.
      if (await page.evaluate(() => !document.hasFocus())) await page.keyboard.press('Shift+Tab');
      assert.equal(await page.evaluate(() => document.activeElement.id), 'submit-upload');
      await page.keyboard.press('Tab');
      if (await page.evaluate(() => !document.hasFocus())) await page.keyboard.press('Tab');
      assert.equal(await page.evaluate(() => document.activeElement.id), 'close-upload');
      await page.keyboard.press('Escape');
      assert.equal(await page.locator('#upload').isVisible(), false);
      assert.equal(await page.evaluate(() => document.activeElement.id), 'open-upload');
    }
    checks.push('responsive_768_390_320_all_views_and_upload_no_overflow', 'upload_keyboard_trap_escape_and_focus_return');
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.join(output, 'browser_acceptance.json'), JSON.stringify({checked_at: new Date().toISOString(), origin, browser: 'Chrome headless', checks, page_errors: errors, synthetic_database: true}, null, 2));
    console.log(JSON.stringify({checks, page_errors: errors}, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
